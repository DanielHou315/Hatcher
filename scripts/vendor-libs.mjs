// Copy the site's fonts into public/_lib/fonts (gitignored). Runs before `dev` and `build`.
// To update a font, bump its @fontsource package; to add one, add its stylesheets to FONTS.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const out = path.join(root, 'public/_lib');

// Font stylesheets, concatenated into /_lib/fonts/fonts.css with their files copied alongside.
const FONTS = [
  '@fontsource-variable/newsreader/opsz.css',
  '@fontsource-variable/newsreader/opsz-italic.css',
  '@fontsource/ibm-plex-sans/400.css',
  '@fontsource/ibm-plex-sans/400-italic.css',
  '@fontsource/ibm-plex-sans/500.css',
  '@fontsource/ibm-plex-sans/600.css',
  '@fontsource/ibm-plex-mono/400.css',
  '@fontsource/ibm-plex-mono/500.css',
];
const fontsOut = path.join(out, 'fonts');
fs.rmSync(fontsOut, { recursive: true, force: true });
fs.mkdirSync(fontsOut, { recursive: true });
let css = '/* Generated by scripts/vendor-libs.mjs from @fontsource packages. */\n';
for (const entry of FONTS) {
  const file = path.join(root, 'node_modules', entry);
  const source = fs.readFileSync(file, 'utf8');
  css += source.replace(/url\(\.\/files\/([^)]+)\)/g, (_, name) => {
    fs.copyFileSync(path.join(path.dirname(file), 'files', name), path.join(fontsOut, name));
    return `url(./${name})`;
  });
}
fs.writeFileSync(path.join(fontsOut, 'fonts.css'), css);
console.log(`vendored ${FONTS.length} font stylesheets into public/_lib/fonts`);
